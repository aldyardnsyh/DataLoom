"""Alembic environment for DataLoom.

Design choices, and why they are the simplest correct ones:

1. **Sync driver (psycopg 3)**. Alembic's ``env.py`` runs DDL; async gives no
   benefit here and adds ``run_sync`` boilerplate. The app itself is async.
2. **URL from the environment only**. ``DATALOOM_DATABASE_URL`` is read here;
   no credentials are ever written to ``alembic.ini``.
3. **Explicit model import**. ``import app.db.models`` is required so that
   ``Base.metadata`` contains every table for autogenerate. Without it,
   autogenerate would propose dropping all tables.
4. **``compare_type`` and ``compare_server_default`` enabled** so future
   autogenerated revisions detect type/default drift.
5. **No RLS manipulation here**. RLS is created by the migration itself; the
   owning role used for migrations bypasses RLS by design (see ADR-004).
"""

from __future__ import annotations

import os
import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context
from sqlalchemy import engine_from_config, pool

# Make ``app`` importable when alembic runs from the ``apps/api`` folder.
BASE_DIR = Path(__file__).resolve().parents[1]
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from app.db.base import Base  # noqa: E402  (path set up above)
import app.db.models  # noqa: E402,F401  (import registers every table)

# Alembic Config object, provides access to values in alembic.ini.
config = context.config

# Configure logging from alembic.ini when present.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# ``target_metadata`` is what autogenerate compares against.
target_metadata = Base.metadata

# Tables owned by LangGraph at runtime. They must NEVER be autogenerated,
# dropped or altered by our migrations.
LANGGRAPH_OWNED_TABLES: frozenset[str] = frozenset(
    {
        "checkpoint_migrations",
        "checkpoints",
        "checkpoint_blobs",
        "checkpoint_writes",
        "store",
        "store_migrations",
        "store_vectors",
    }
)


def _database_url() -> str:
    """Resolve the sync database URL from the environment.

    Precedence:
    1. ``DATALOOM_DATABASE_URL`` - explicit override, always wins.
    2. ``DATABASE_URL`` - common convention on managed providers.
    A ``postgresql+asyncpg://`` URL is rewritten to ``postgresql+psycopg://``
    because this env.py is synchronous.
    """
    raw = os.environ.get("DATALOOM_DATABASE_URL") or os.environ.get("DATABASE_URL")
    if not raw:
        raise RuntimeError(
            "DATALOOM_DATABASE_URL (or DATABASE_URL) belum diset. "
            "Contoh: postgresql+psycopg://user:pass@host:5432/dataloom"
        )
    if raw.startswith("postgresql+asyncpg://"):
        raw = raw.replace("postgresql+asyncpg://", "postgresql+psycopg://", 1)
    if raw.startswith("postgres://"):
        raw = raw.replace("postgres://", "postgresql+psycopg://", 1)
    return raw


def include_object(object_, name, type_, reflected, compare_to):  # noqa: ANN001
    """Exclude LangGraph-owned tables from autogenerate comparisons."""
    if type_ == "table" and name in LANGGRAPH_OWNED_TABLES:
        return False
    return True


def run_migrations_offline() -> None:
    """Emit SQL to stdout without connecting (``alembic upgrade --sql``)."""
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_object=include_object,
        include_schemas=False,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Connect and run migrations against a real database."""
    section = config.get_section(config.config_ini_section, {})
    # Inject the resolved URL so alembic.ini stays secret-free.
    section["sqlalchemy.url"] = _database_url()

    connectable = engine_from_config(
        section,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
        future=True,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            compare_type=True,
            compare_server_default=True,
            include_object=include_object,
            include_schemas=False,
            # Keep transactional DDL: Postgres supports it, so a failed
            # migration leaves the schema untouched.
            transaction_per_migration=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
