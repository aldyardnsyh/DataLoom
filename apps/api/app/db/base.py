"""SQLAlchemy 2.0 declarative base and shared column helpers.

No magic here: one ``Base``, three mixins, and the naming convention Alembic
needs so that constraint names are stable across migrations.

Tenancy convention (see ADR-004):
- Every project-scoped table carries ``org_id`` (denormalised where the row is
  reachable only through a parent, e.g. ``run_nodes``).
- RLS policies compare ``org_id`` with ``current_setting('app.current_org_id')``.
- SQLAlchemy models DO NOT set the session variable themselves; the request
  dependency does it once per transaction (see ``docs/ARCHITECTURE.md``).
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, func, text
from sqlalchemy.dialects.postgresql import UUID as PgUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

#: Deterministic constraint naming. Alembic autogenerate compares by name, so
#: this must stay identical for the lifetime of the project.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for every DataLoom table."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUID primary key generated by Postgres (``gen_random_uuid()``, pg13+)."""
    return mapped_column(
        PgUUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )


def uuid_fk(
    target: str,
    *,
    ondelete: str = "CASCADE",
    nullable: bool = False,
    index: bool = True,
) -> Mapped[uuid.UUID]:
    """UUID foreign key with an explicit ON DELETE action."""
    from sqlalchemy import ForeignKey

    return mapped_column(
        PgUUID(as_uuid=True),
        ForeignKey(target, ondelete=ondelete),
        nullable=nullable,
        index=index,
    )


class OrgScopedMixin:
    """Adds the denormalised ``org_id`` used by every RLS policy.

    Keep this column FIRST in table definitions out of habit; it makes
    ``grep org_id`` a reliable way to audit tenant coverage.
    """

    org_id: Mapped[uuid.UUID] = mapped_column(
        PgUUID(as_uuid=True),
        index=True,
        nullable=False,
        doc="Tenant key. Mirrors the parent row's org_id; enforced by RLS.",
    )


class TimestampMixin:
    """``created_at`` / ``updated_at`` as TIMESTAMPTZ with server defaults."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


class CreatedAtMixin:
    """``created_at`` only, for append-only tables (logs, events)."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )


__all__ = [
    "Base",
    "CreatedAtMixin",
    "NAMING_CONVENTION",
    "OrgScopedMixin",
    "TimestampMixin",
    "uuid_fk",
    "uuid_pk",
]
