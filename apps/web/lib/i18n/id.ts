/** Human readable label for any run/node status value. */
export function statusLabel(status: string): string {
  const map: Record<string, string> = {
    draft: t.status.draft,
    validated: t.status.validated,
    queued: t.status.queued,
    running: t.status.running,
    succeeded: t.status.succeeded,
    failed: t.status.failed,
    retrying: t.status.retrying,
    needs_attention: t.status.needsAttention,
    cancelled: t.status.cancelled,
    pending: t.status.pending,
    approved: t.status.approved,
    rejected: t.status.rejected,
    connected: t.status.connected,
    active: t.status.active,
    error: t.status.error,
    paused: t.status.paused,
    waiting_approval: t.status.waitingApproval,
    insufficient_evidence: t.status.insufficientEvidence,
    skipped: t.status.pending,
  };
  return map[status] ?? status;
}



